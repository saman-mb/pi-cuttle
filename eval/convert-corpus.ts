/**
 * Convert eval/corpus.jsonl to Promptfoo-compatible YAML format.
 *
 * Usage: node --experimental-strip-types eval/convert-corpus.ts
 * Output: eval/corpus-promptfoo.yaml (overwrites if exists)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import type { Tier } from "../src/types.ts";

const here = dirname(fileURLToPath(import.meta.url));
const corpusPath = join(here, "corpus.jsonl");
const outputPath = join(here, "corpus-promptfoo.yaml");

interface CorpusEntry {
	prompt: string;
	label?: Tier;
	expectedTier?: Tier;
	expectedThinkingLevel?: string;
	features?: string[];
	notes?: string;
}

function escapeYamlString(s: string): string {
	// Quote strings that contain special YAML characters
	if (s.includes(":") || s.includes("#") || s.includes("{") || s.includes("}") || s.includes("[") || s.includes("]") || s.includes(",") || s.includes("&") || s.includes("*") || s.includes("!") || s.includes("|") || s.includes(">") || s.includes("'") || s.includes('"') || s.includes("%") || s.includes("@") || s.includes("`")) {
		return `"${s.replace(/"/g, '\\"')}"`;
	}
	return s;
}

function loadCorpus(): CorpusEntry[] {
	const text = readFileSync(corpusPath, "utf8");
	const entries: CorpusEntry[] = [];
	for (const line of text.split("\n")) {
		if (!line.trim()) continue;
		try {
			const entry = JSON.parse(line) as CorpusEntry;
			// Normalize label to expectedTier for consistency
			if (entry.label && !entry.expectedTier) {
				entry.expectedTier = entry.label;
			}
			entries.push(entry);
		} catch {
			// Skip malformed lines
		}
	}
	return entries;
}

function convertToPromptfoo(entries: CorpusEntry[]): string {
	const lines: string[] = [];
	lines.push("# Auto-generated by convert-corpus.ts");
	lines.push("# Do not edit manually; edit corpus.jsonl directly and re-run the converter.");
	lines.push("");
	lines.push("description: pi-cuttle routing evaluation - converted from corpus.jsonl");
	lines.push("");
	lines.push("prompts:");
	lines.push("  - \"{{prompt}}\"");
	lines.push("");
	lines.push("providers:");
	lines.push("  - id: file://eval/pi-cuttle-provider.ts");
	lines.push("");
	lines.push("tests:");

	for (const entry of entries) {
		lines.push("  - vars:");
		lines.push(`      prompt: ${escapeYamlString(entry.prompt)}`);
		if (entry.expectedTier) {
			lines.push(`    assert:`);
			lines.push(`      - type: javascript`);
			lines.push(`        value: output.tier === '${entry.expectedTier}'`);
			if (entry.notes) {
				lines.push(`        # ${entry.notes}`);
			}
		} else if (entry.features || entry.notes) {
			lines.push(`    # Features: ${entry.features?.join(", ") ?? "none"}`);
			if (entry.notes) {
				lines.push(`    # Notes: ${entry.notes}`);
			}
		}
	}

	lines.push("");
	return lines.join("\n");
}

function main() {
	const entries = loadCorpus();
	console.log(`Loaded ${entries.length} entries from corpus.jsonl`);

	const yaml = convertToPromptfoo(entries);
	writeFileSync(outputPath, yaml, "utf8");
	console.log(`Wrote ${outputPath}`);
}

main();
