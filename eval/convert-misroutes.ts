/**
 * Convert eval/misroutes.jsonl to a Promptfoo-compatible config.
 *
 * Usage: node --experimental-strip-types eval/convert-misroutes.ts
 * Output: eval/misroutes-promptfoo.yaml
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const inputPath = join(here, "misroutes.jsonl");
const outputPath = join(here, "misroutes-promptfoo.yaml");

interface MisrouteFixture {
	prompt: string;
	expectedTier: string;
	actualTier: string;
	actualModel: string;
	flavor: string;
	score?: number;
	reason: string;
	notes: string;
	source: string;
}

function escapeYamlString(s: string): string {
	if (s.includes(":") || s.includes("#") || s.includes("{") || s.includes("}") || s.includes("[") || s.includes("]") || s.includes(",") || s.includes("&") || s.includes("*") || s.includes("!") || s.includes("|") || s.includes(">") || s.includes("'") || s.includes('"') || s.includes("%") || s.includes("@") || s.includes("`")) {
		return `"${s.replace(/"/g, '\\"')}"`;
	}
	return s;
}

function loadMisroutes(): MisrouteFixture[] {
	try {
		const text = readFileSync(inputPath, "utf8");
		const entries: MisrouteFixture[] = [];
		for (const line of text.split("\n")) {
			if (!line.trim()) continue;
			try {
				entries.push(JSON.parse(line) as MisrouteFixture);
			} catch {
				// skip malformed lines
			}
		}
		return entries;
	} catch {
		return [];
	}
}

function convertToPromptfoo(entries: MisrouteFixture[]): string {
	const lines: string[] = [];
	lines.push("# Auto-generated by convert-misroutes.ts");
	lines.push("# Do not edit manually; run npm run eval:export-misroutes first.");
	lines.push("");
	lines.push("description: pi-cuttle misroute fixtures from LangFuse annotations");
	lines.push("");
	lines.push("prompts:");
	lines.push("  - \"{{prompt}}\"");
	lines.push("");
	lines.push("providers:");
	lines.push("  - id: file://pi-cuttle-provider.ts");
	lines.push("");
	lines.push("tests:");

	for (const entry of entries) {
		lines.push("  - vars:");
		lines.push(`      prompt: ${escapeYamlString(entry.prompt)}`);
		lines.push(`      flavor: ${entry.flavor ?? "auto"}`);
		lines.push(`      thinkingLevel: high`);
		lines.push(`    assert:`);
		lines.push(`      - type: javascript`);
		lines.push(`        value: output.tier === '${entry.expectedTier}'`);
		lines.push(`      - type: javascript`);
		lines.push(`        value: output.modelId === '${entry.actualModel}'`);
		lines.push(`    metadata:`);
		lines.push(`      category: misroute`);
		lines.push(`      actualTier: ${entry.actualTier}`);
		lines.push(`      score: ${entry.score ?? "null"}`);
		lines.push(`      notes: ${escapeYamlString(entry.notes)}`);
	}

	return lines.join("\n") + "\n";
}

const entries = loadMisroutes();
if (entries.length === 0) {
	console.log(`No misroutes found at ${inputPath}; writing empty config.`);
	writeFileSync(outputPath, convertToPromptfoo([]));
} else {
	writeFileSync(outputPath, convertToPromptfoo(entries));
	console.log(`Converted ${entries.length} misroute(s) to ${outputPath}`);
}
